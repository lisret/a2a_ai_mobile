#!/usr/bin/env node
/**
 * pin-asr-artifacts.js
 *
 * 下载 Sherpa-ONNX 官方 ASR 产物（GitHub Release，绝不走 jsDelivr / unpkg / cdnjs），
 * 按字节数与 SHA-256 钉死，生成 src/features/task/asr/AsrArtifactPins.ts。
 *
 * 产物：
 *   - builtin: 流式 Zipformer 14M（随 APK 走 assets，体积小）
 *   - upgrade: SenseVoice 离线大模型（Wi-Fi 静默升级，不进 APK）
 *   - sherpa-onnx Android AAR（放入 android/app/libs/，gitignore）
 *
 * 仓库只提交 AsrArtifactPins.ts 与本脚本；50MB+ 权重与 AAR 均不入库。
 * 开发者/CI 构建前先跑：`node scripts/pin-asr-artifacts.js`
 */

const {execFileSync} = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const WORK_DIR = path.join(PROJECT_ROOT, 'build', 'asr-pins');
const ASSETS_BUILTIN_DIR = path.join(
  PROJECT_ROOT,
  'android',
  'app',
  'src',
  'main',
  'assets',
  'nono-asr',
  'builtin',
);
const LIBS_DIR = path.join(PROJECT_ROOT, 'android', 'app', 'libs');
const PINS_OUT = path.join(
  PROJECT_ROOT,
  'src',
  'features',
  'task',
  'asr',
  'AsrArtifactPins.ts',
);

const RELEASE = 'https://github.com/k2-fsa/sherpa-onnx/releases/download';

const PACKS = {
  builtin: {
    id: 'builtin',
    title: 'Zipformer 14M zh (streaming)',
    archiveUrl: `${RELEASE}/asr-models/sherpa-onnx-streaming-zipformer-zh-14M-2023-02-23.tar.bz2`,
    archiveName: 'sherpa-onnx-streaming-zipformer-zh-14M-2023-02-23.tar.bz2',
    extractDir: 'sherpa-onnx-streaming-zipformer-zh-14M-2023-02-23',
  },
  upgrade: {
    id: 'upgrade',
    title: 'SenseVoice zh/en/ja/ko/yue (offline)',
    archiveUrl: `${RELEASE}/asr-models/sherpa-onnx-sense-voice-zh-en-ja-ko-yue-2024-07-17.tar.bz2`,
    archiveName: 'sherpa-onnx-sense-voice-zh-en-ja-ko-yue-2024-07-17.tar.bz2',
    extractDir: 'sherpa-onnx-sense-voice-zh-en-ja-ko-yue-2024-07-17',
  },
};

const AAR_VERSION = '1.13.6';
const AAR_URL = `${RELEASE}/v${AAR_VERSION}/sherpa-onnx-${AAR_VERSION}.aar`;

function log(msg) {
  process.stdout.write(`[pin-asr] ${msg}\n`);
}

function sha256File(file) {
  const hash = crypto.createHash('sha256');
  hash.update(fs.readFileSync(file));
  return hash.digest('hex');
}

function download(url, dest) {
  log(`downloading ${url}`);
  // -C - 断点续传：throttled CDN 上可反复重跑直到完成。
  execFileSync(
    'curl',
    ['-fL', '-C', '-', '--retry', '20', '--retry-delay', '5', '-o', dest, url],
    {stdio: 'inherit'},
  );
}

function extract(archive, intoDir) {
  fs.mkdirSync(intoDir, {recursive: true});
  log(`extracting ${path.basename(archive)}`);
  execFileSync('tar', ['-xjf', archive, '-C', intoDir], {stdio: 'inherit'});
}

/** 递归收集 *.onnx 与 tokens.txt，name 为相对 packDir 的路径。 */
function collectFiles(packDir) {
  const out = [];
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(abs);
      } else if (entry.name.endsWith('.onnx') || entry.name === 'tokens.txt') {
        out.push({
          name: path.relative(packDir, abs),
          bytes: fs.statSync(abs).size,
          sha256: sha256File(abs),
        });
      }
    }
  };
  walk(packDir);
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

function copyDir(src, dest) {
  fs.rmSync(dest, {recursive: true, force: true});
  fs.mkdirSync(dest, {recursive: true});
  for (const entry of fs.readdirSync(src, {withFileTypes: true})) {
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDir(s, d);
    } else {
      fs.copyFileSync(s, d);
    }
  }
}

function renderPins(pins) {
  const header =
    '// AUTO-GENERATED by scripts/pin-asr-artifacts.js — do not edit by hand.\n' +
    '// Sherpa-ONNX ASR archives pinned by size + SHA-256 (GitHub Release only).\n\n';
  const iface = `export interface AsrFilePin {
  name: string;
  bytes: number;
  sha256: string;
}

export interface AsrPackPin {
  id: 'builtin' | 'upgrade';
  title: string;
  archiveUrl: string;
  archiveBytes: number;
  archiveSha256: string;
  files: AsrFilePin[];
}

`;
  const body = `export const ASR_PINS: {builtin: AsrPackPin; upgrade: AsrPackPin} = ${JSON.stringify(
    pins,
    null,
    2,
  )} as const;\n`;
  return header + iface + body;
}

function main() {
  fs.mkdirSync(WORK_DIR, {recursive: true});
  fs.mkdirSync(LIBS_DIR, {recursive: true});

  const pins = {};
  for (const key of ['builtin', 'upgrade']) {
    const pack = PACKS[key];
    const archive = path.join(WORK_DIR, pack.archiveName);
    download(pack.archiveUrl, archive);

    const archiveBytes = fs.statSync(archive).size;
    const archiveSha256 = sha256File(archive);

    const extractRoot = path.join(WORK_DIR, key);
    extract(archive, extractRoot);
    const packDir = path.join(extractRoot, pack.extractDir);
    if (!fs.existsSync(packDir)) {
      throw new Error(`expected extract dir missing: ${packDir}`);
    }
    const files = collectFiles(packDir);
    if (!files.some(f => f.name.endsWith('tokens.txt'))) {
      throw new Error(`no tokens.txt found in ${pack.id}`);
    }

    pins[key] = {
      id: pack.id,
      title: pack.title,
      archiveUrl: pack.archiveUrl,
      archiveBytes,
      archiveSha256,
      files,
    };
    log(`${pack.id}: ${archiveBytes} bytes, ${files.length} model files`);

    // builtin 拷入 APK assets（upgrade 不进 APK）。
    if (key === 'builtin') {
      copyDir(packDir, ASSETS_BUILTIN_DIR);
      log(`copied builtin model into ${ASSETS_BUILTIN_DIR}`);
    }
  }

  // Sherpa Android AAR（gitignore，构建前必须存在）。
  download(AAR_URL, path.join(LIBS_DIR, 'sherpa-onnx.aar'));

  fs.mkdirSync(path.dirname(PINS_OUT), {recursive: true});
  fs.writeFileSync(PINS_OUT, renderPins(pins), 'utf8');
  log(`wrote ${PINS_OUT}`);
}

main();
